def _fallback(text, ctx):
    """Unknown line: hide plain info, soften problems."""
    mod = MODULES.get(ctx.get("module") or "", "")
    where = f"{mod}: " if mod else ""

    def cap(line):
        icon, _, rest = line.partition(" ")
        return f"{icon} {rest[:1].upper()}{rest[1:]}" if not mod else line

    if text.startswith(("❌", "🛑", "💥")) or "Traceback" in text:
        return cap(f"❌ {where}ошибка. Если повторяется — нажми «Сообщить о проблеме» в Настройках")
    if text.startswith("⚠️"):
        return cap(f"⚠️ {where}небольшая заминка, Buffy повторит сам")
    return None


def humanize(text, ctx=None):
    """Friendly version of one raw log line, or None to hide it from the journal."""
    ctx = ctx if ctx is not None else {}
    text = str(text or "").strip()
    started = re.match(r"^▶️ Модуль «(\w+)»", text)
    if started:
        ctx["module"] = started.group(1)
    for patterns, template in RULES:
        m = next((hit for hit in (rx.search(text) for rx in patterns) if hit), None)
        if not m:
            continue
        if template is None:
            return None
        if callable(template):
            return template(m, {**ctx, "text": text})
        return template.format(**{k: (v or "").strip() for k, v in m.groupdict().items()})
    return _fallback(text, ctx)
