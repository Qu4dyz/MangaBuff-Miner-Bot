def _from_tr(key, template):
    """Regexes for every translation of a tr() key: '{count}' -> named group."""
    variants = []
    for lang in LANGUAGES.values():
        raw = lang.get(key)
        if not raw:
            continue
        parts = re.split(r"\{(\w+)\}", raw)
        rx = "".join(re.escape(p) if i % 2 == 0 else f"(?P<{p}>.+?)" for i, p in enumerate(parts))
        variants.append("^" + rx + "$")
    return [re.compile(v, re.S) for v in dict.fromkeys(variants)], template


def _rx(pattern, template):
    return [re.compile(pattern, re.S)], template


